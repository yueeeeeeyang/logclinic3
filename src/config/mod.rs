//! 应用配置功能域聚合入口。
//!
//! 业务意图：
//! - 配置域对 `app`、AI 对话存储和测试暴露稳定的 crate 内接口，同时把路径、普通偏好和模型配置拆成独立文件。
//! - 文件格式、默认值、损坏配置回退和写入错误处理保持不变；本模块只负责模块边界和受控重导出。
//!
//! 边界条件：
//! - 所有配置类型和函数仍限制在 crate 内部使用，不形成公开 API，避免磁盘格式在未确认迁移策略前被外部依赖。
//! - 路径模块不创建目录，具体写入函数按需创建父目录并处理 macOS/Windows 权限差异。

/// 模型配置、校验和测试请求。
mod model;
/// 配置目录和配置文件路径。
mod paths;
/// 窗口、主题、日志字号、minimap、线程过滤和快搜偏好。
mod preferences;

